// Compiles the translation sources test/i18n/src/*.tsv into src/shared/i18n/hi.js and mr.js.
// Source format, one string per line:   English | Hindi | Marathi   (a TAB also works as the separator)
//   "="  in a language column  -> keep the English text unchanged (brand names, formats, units)
//   "-"  in the Hindi column     -> not UI text (code, data); excluded from coverage (test/i18n/ignore.json)
//   "#"  at the start of a line  -> comment
// Placeholders such as {n} or {name} must appear unchanged in every translation.
'use strict';
const fs = require('fs'), path = require('path');
const srcDir = path.join(__dirname, 'i18n', 'src');
const outDir = path.join(__dirname, '..', 'src', 'shared', 'i18n');
const dict = { hi: {}, mr: {} }, ignore = new Set(), problems = [], droppedPh = [];
const norm = s => s.replace(/\s+/g, ' ').trim();
const files = fs.readdirSync(srcDir).filter(f => /\.(tsv|txt)$/.test(f)).sort();
for (const f of files) {
  fs.readFileSync(path.join(srcDir, f), 'utf8').split(/\r?\n/).forEach((line, i) => {
    if (!line.trim() || line.startsWith('#')) return;
    const cols = line.includes('\t') ? line.split('\t') : line.split(/\s+\|(?:\s+|$)/);
    const en = norm(cols[0] || ''); if (!en) return;
    const hi = norm(cols[1] || ''), mr = norm(cols[2] || '');
    if (hi === '-') { ignore.add(en); return; }
    for (const [lang, v] of [['hi', hi], ['mr', mr]]) {
      if (!v) { problems.push(`${f}:${i + 1} missing ${lang}: ${en}`); continue; }
      const val = v === '=' ? en : v;
      // Every placeholder in a translation must exist in the English key. A translation may drop an English
      // plural-suffix placeholder (e.g. "file{p1}" -> "फ़ाइलें"), which is reported as information only.
      const enSet = new Set(en.match(/\{[A-Za-z_]\w*\}/g) || []), vList = val.match(/\{[A-Za-z_]\w*\}/g) || [];
      const extra = vList.filter(x => !enSet.has(x)), dropped = [...enSet].filter(x => !vList.includes(x));
      if (extra.length) problems.push(`${f}:${i + 1} unknown placeholder ${extra.join(',')} (${lang}): ${en}  ->  ${val}`);
      if (dropped.length) droppedPh.push(`${lang} ${en}: ${dropped.join(',')}`);
      if (dict[lang][en] !== undefined && dict[lang][en] !== val) problems.push(`${f}:${i + 1} duplicate key with a different ${lang} value: ${en}`);
      dict[lang][en] = val;
    }
  });
}
const header = lang => `// BTS Creative — ${lang === 'hi' ? 'Hindi (हिन्दी)' : 'Marathi (मराठी)'} interface strings, keyed by the exact English text.\n// Generated by test/i18n-build.js from test/i18n/src/*.tsv — edit the .tsv sources, then run: node test/i18n-build.js\n`;
for (const lang of ['hi', 'mr']) {
  const keys = Object.keys(dict[lang]).sort();
  const body = keys.map(k => JSON.stringify(k) + ':' + JSON.stringify(dict[lang][k])).join(',\n');
  fs.writeFileSync(path.join(outDir, lang + '.js'), header(lang) + `I18N.register('${lang}', {\n${body}\n});\n`);
  console.log(lang + ':', keys.length, 'entries');
}
fs.writeFileSync(path.join(__dirname, 'i18n', 'ignore.json'), JSON.stringify([...ignore].sort(), null, 0));
console.log('ignored (not UI text):', ignore.size, '· translations that drop a placeholder (plural suffixes):', droppedPh.length);
if (process.argv.includes('--dropped')) console.log(droppedPh.join('\n'));
if (problems.length) { console.log(problems.length + ' problem(s):\n' + problems.slice(0, 80).join('\n')); process.exitCode = 1; }
